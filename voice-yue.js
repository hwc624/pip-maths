  /* 把粵語台詞掛到每一句：語氣（tone）沿用中文版同一段 */
  function apply(V) {
    const missing = [], mismatch = [];
    Object.keys(V.LINES).forEach(id => {
      const L = V.LINES[id], y = YUE[id];
      if (!y) { missing.push(id); L.yue = L.zh; return; }
      if (y.length !== L.zh.length) mismatch.push(id + " " + y.length + "≠" + L.zh.length);
      L.yue = y.map((t, i) => ({ text: t, tone: (L.zh[i] || L.zh[L.zh.length - 1]).tone }));
    });
    return { missing, mismatch };
  }

